const { createHash } = require('node:crypto');
const { mkdir, readFile, writeFile } = require('node:fs/promises');
const path = require('node:path');
const { homedir } = require('node:os');

function loadSharp() {
  const bundle = path.join(homedir(), '.cache', 'codex-runtimes', 'codex-primary-runtime', 'dependencies', 'node', 'node_modules');
  try {
    return require(require.resolve('sharp', { paths: [__dirname, bundle] }));
  } catch (error) {
    if (error.code !== 'MODULE_NOT_FOUND') throw error;
    throw Error('Sharp is required. Use the Codex workspace runtime or install Sharp for Node.js.', { cause: error });
  }
}

const sharp = loadSharp();

const site = path.resolve(__dirname, '../../site');
const active = path.join(site, 'themes/active.json');
const locales = 'ru en es pt-BR tr fil id ms th vi hi'.split(' ');
const colorNames = [
  'text', 'background', 'overlay-top', 'overlay-middle', 'overlay-bottom',
  'glass-top', 'glass-middle', 'glass-bottom', 'glass-border', 'glass-highlight', 'glass-shadow',
  'avatar-border', 'avatar-shadow', 'button', 'button-border', 'button-hover'
];
const ink = '#061B2B';
const white = '#FFFFFF';

async function save(file, data) {
  const current = await readFile(file).catch(error => {
    if (error.code !== 'ENOENT') throw error;
  });
  const next = Buffer.from(data);
  if (!current?.equals(next)) await writeFile(file, next);
}

function replace(html, pattern, replacement, file) {
  if (!pattern.test(html)) throw Error('Missing expected markup in ' + file + ': ' + pattern);
  return html.replace(pattern, replacement);
}

async function asset(relativePath) {
  if (typeof relativePath !== 'string' || !relativePath ||
      relativePath.split('/').some(segment => !segment || segment === '.' || segment === '..') ||
      /[\\:"?#<>\x00-\x1f]/.test(relativePath)) {
    throw Error('Use a relative path inside site/ for each image');
  }
  const data = await readFile(path.join(site, relativePath));
  const image = await sharp(data).metadata();
  if (!image.width || !image.height) throw Error('Invalid image: ' + relativePath);
  return { data, url: relativePath.split('/').map(encodeURIComponent).join('/') };
}

function icon(mark, size, fraction, foreground, background, accent, corner = 0) {
  const width = size * fraction;
  const height = width * 100 / 147;
  const monogram = mark.replace('<svg ', '<svg x="' + ((size - width) / 2) + '" y="' + ((size - height) / 2) +
    '" width="' + width + '" height="' + height + '" ').replace('{{v}}', foreground).replace('{{accent}}', accent);
  return '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size +
    '" viewBox="0 0 ' + size + ' ' + size + '"><rect width="' + size + '" height="' + size +
    '" rx="' + corner + '" fill="' + background + '"/>' + monogram.trim() + '</svg>\n';
}

async function apply() {
  const selected = process.argv[2] ? path.resolve(process.argv[2]) : active;
  const theme = JSON.parse(await readFile(selected, 'utf8'));
  if (![theme.name, theme.version].every(value => typeof value === 'string' && value.trim()) ||
      !/^#[\da-f]{6}$/i.test(theme.accent) ||
      !colorNames.every(name => /^#[\da-f]{6}(?:[\da-f]{2})?$/i.test(theme.colors?.[name] || ''))) {
    throw Error('Theme requires a name, a version, a six-digit accent and the homepage palette from sea.json');
  }

  const avatar = await asset(theme.avatar);
  const background = theme.background == null ? avatar : await asset(theme.background);
  const mark = await readFile(path.join(__dirname, 'v1.svg'), 'utf8');
  const json = JSON.stringify(theme, null, 2) + '\n';
  const version = createHash('sha256').update(json).update(avatar.data).update(background.data)
    .update(mark).update(await readFile(__filename)).digest('hex').slice(0, 12);
  const cache = '?v=' + version;
  const colors = colorNames.map(name => '  --home-' + name + ': ' + theme.colors[name] + ';');
  const homeCss = ['/* Generated by tools/theme/apply.cjs. */', '.home {',
    '  --home-background-image: url("/' + background.url + cache + '");',
    '  --home-accent: ' + theme.accent + ';', ...colors, '}', ''].join('\n');

  const writes = new Map([
    [path.join(site, 'themes/home.css'), homeCss],
    [path.join(site, 'assets/tabs/vladimir1-light.svg'), icon(mark, 64, .72, ink, white, theme.accent, 13)],
    [path.join(site, 'assets/tabs/vladimir1-dark.svg'), icon(mark, 64, .72, white, ink, theme.accent, 13)]
  ]);
  const shortcuts = [
    ['any-192', 192, .68], ['any-512', 512, .68],
    ['maskable-192', 192, .62], ['maskable-512', 512, .62], ['apple-180', 180, .68]
  ];
  for (const [key, size, fraction] of shortcuts) {
    const svg = icon(mark, size, fraction, ink, white, theme.accent);
    const png = await sharp(Buffer.from(svg)).png().toBuffer();
    writes.set(path.join(site, 'assets/shortcuts/vladimir1-' + key + '.png'), png);
  }

  for (const locale of ['', ...locales]) {
    const home = path.join(site, locale, 'index.html');
    const manifestName = locale ? 'shortcut.webmanifest' : 'manifest.webmanifest';
    const manifest = path.join(site, locale, manifestName);
    const prefix = locale ? '../' : '';
    const favicon = mode => '<link rel="icon" href="' + prefix + 'assets/tabs/vladimir1-' + mode +
      '.svg' + cache + '" type="image/svg+xml" sizes="any"' +
      (mode === 'dark' ? ' media="(prefers-color-scheme: dark)"' : '') + '>';
    const apple = '<link rel="apple-touch-icon" href="' + prefix +
      'assets/shortcuts/vladimir1-apple-180.png' + cache + '">';

    let html = await readFile(home, 'utf8');
    html = replace(html, /<link rel="icon" href="[^"]*vladimir1(?:-light)?\.svg[^"]*"[^>]*>(?:<link rel="icon" href="[^"]*vladimir1-dark\.svg[^"]*"[^>]*>)?/,
      favicon('light') + favicon('dark'), home);
    const appleLink = /<link rel="apple-touch-icon"[^>]*>/;
    html = appleLink.test(html) ? html.replace(appleLink, apple) :
      replace(html, /<link rel="manifest"/, apple + '<link rel="manifest"', home);
    if (locale) {
      html = replace(html, /(<link rel="stylesheet" href="\.\.\/src\/site\.css[^"]*">)(?:<link rel="stylesheet" href="\.\.\/themes\/home\.css[^"]*">)?/,
        '$1<link rel="stylesheet" href="../themes/home.css' + cache + '">', home);
      html = replace(html, /(<div class="portrait"><img src=")[^"]+/, '$1../' + avatar.url + cache, home);
    }
    html = replace(html, /(<link rel="manifest" href=")[^"]+/, '$1' + manifestName + cache, home);
    writes.set(home, html);

    const manifestSource = await readFile(manifest, 'utf8');
    const metadata = JSON.parse(manifestSource);
    for (const entry of metadata.icons) {
      const key = entry.purpose + '-' + entry.sizes.split('x')[0];
      if (!shortcuts.some(([name]) => name === key)) throw Error('Unexpected manifest icon: ' + key);
      entry.src = '/assets/shortcuts/vladimir1-' + key + '.png' + cache;
    }
    writes.set(manifest, JSON.stringify(metadata) + (manifestSource.endsWith('\r\n') ? '\r\n' : '\n'));
  }

  await mkdir(path.dirname(active), { recursive: true });
  for (const [file, data] of writes) await save(file, data);
  await save(active, json);
  console.log('Applied ' + theme.name + ' (' + theme.version + ', ' + version + ')');
}

apply().catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});
